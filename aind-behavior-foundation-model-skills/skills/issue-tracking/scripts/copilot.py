#!/usr/bin/env python3
"""Drive a Copilot review loop on an AllenNeuralDynamics PR.

    copilot.py request <repo> <pr>                     request (or re-request) a Copilot review
    copilot.py status  <repo> <pr>                     Copilot reviews so far, oldest first
    copilot.py threads <repo> <pr>                     unresolved review threads
    copilot.py reply   <repo> <pr> <comment_id> <body-file>
    copilot.py resolve <thread_id> [ADDRESSED|WONT_FIX|INVALID|OUTDATED]

Needs GITHUB_TOKEN with `repo` scope, SSO-authorized for the org (same as board.py). Output
is JSON, so a poll loop can count reviews with `status ... | jq length`.

A review lands ~4-5 minutes after `request`; nothing re-requests it after a push, so call
`request` again. Reply on a thread before resolving it; `reply` appends the Claude Code footer.
The loop's rules (round limit, which reason to resolve with) are in ../SKILL.md.
"""
import json
import os
import sys
import urllib.error
import urllib.request

ORG = "AllenNeuralDynamics"
COPILOT_BOT_ID = "BOT_kgDOCnlnWA"     # the Bot node in AllenNeuralDynamics; see SKILL.md if it changes
FOOTER = "\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_"
REASONS = ("ADDRESSED", "WONT_FIX", "INVALID", "OUTDATED")


def _token():
    tok = os.environ.get("GITHUB_TOKEN")
    if not tok:
        sys.exit("GITHUB_TOKEN is not set.")
    return tok


def _request(url, payload=None, method="GET"):
    req = urllib.request.Request(
        url, method=method,
        data=None if payload is None else json.dumps(payload).encode(),
        headers={"Authorization": "Bearer " + _token(),
                 "Accept": "application/vnd.github+json",
                 "Content-Type": "application/json"})
    try:
        with urllib.request.urlopen(req) as resp:
            body = resp.read()
            return json.loads(body) if body.strip() else None
    except urllib.error.HTTPError as exc:
        detail = exc.read().decode(errors="replace")[:400]
        if exc.code == 403 and "SAML" in detail:
            sys.exit("403: the PAT is not SSO-authorized for " + ORG
                     + ". Authorize it in the token settings, then rerun.")
        sys.exit("HTTP {}: {}".format(exc.code, detail))


def rest(path, payload=None, method="GET"):
    return _request("https://api.github.com/" + path, payload, method)


def gql(query, variables):
    """GraphQL call. Errors arrive with HTTP 200, so check the errors array."""
    out = _request("https://api.github.com/graphql",
                   {"query": query, "variables": variables}, method="POST")
    if out.get("errors"):
        sys.exit("GraphQL error: " + json.dumps(out["errors"])[:500])
    return out["data"]


def pr_node_id(repo, number):
    q = "query($o:String!,$r:String!,$n:Int!){repository(owner:$o,name:$r){pullRequest(number:$n){id}}}"
    return gql(q, {"o": ORG, "r": repo, "n": number})["repository"]["pullRequest"]["id"]


def request(repo, number):
    # REST requested_reviewers rejects the bot (422) and never lists it; GraphQL does both.
    q = """mutation($pr:ID!,$b:[ID!]!){requestReviews(input:{pullRequestId:$pr,botIds:$b,union:true}){
      pullRequest{reviewRequests(first:10){nodes{requestedReviewer{... on Bot{login}}}}}}}"""
    out = gql(q, {"pr": pr_node_id(repo, number), "b": [COPILOT_BOT_ID]})
    logins = [n["requestedReviewer"].get("login") for n in
              out["requestReviews"]["pullRequest"]["reviewRequests"]["nodes"] if n["requestedReviewer"]]
    return {"requested": "copilot-pull-request-reviewer" in logins, "pending_reviewers": logins}


def status(repo, number):
    reviews, page = [], 1
    while True:                       # every page: later Copilot rounds must not be dropped
        batch = rest(f"repos/{ORG}/{repo}/pulls/{number}/reviews?per_page=100&page={page}")
        reviews += batch
        if len(batch) < 100:
            break
        page += 1
    # REST login is "Copilot"; GraphQL's is "copilot-pull-request-reviewer"
    return [{"id": r["id"], "commit": r["commit_id"], "state": r["state"],
             "submitted_at": r["submitted_at"], "body": r["body"]}
            for r in reviews if "copilot" in r["user"]["login"].lower()]


def threads(repo, number):
    q = """query($o:String!,$r:String!,$n:Int!,$c:String){repository(owner:$o,name:$r){pullRequest(number:$n){
      reviewThreads(first:100,after:$c){pageInfo{hasNextPage endCursor} nodes{id isResolved isOutdated path line
        comments(first:50){nodes{databaseId author{login} body}}}}}}}"""
    nodes, cursor = [], None
    while True:                       # every page: an unresolved thread may sit past the first 100
        page = gql(q, {"o": ORG, "r": repo, "n": number, "c": cursor})["repository"]["pullRequest"]["reviewThreads"]
        nodes += page["nodes"]
        if not page["pageInfo"]["hasNextPage"]:
            break
        cursor = page["pageInfo"]["endCursor"]
    return [{"thread": t["id"], "path": t["path"], "line": t["line"], "outdated": t["isOutdated"],
             "comments": [{"id": c["databaseId"], "author": (c["author"] or {}).get("login"),
                           "body": c["body"]} for c in t["comments"]["nodes"]]}
            for t in nodes if not t["isResolved"]]


def reply(repo, number, comment_id, body):
    rest(f"repos/{ORG}/{repo}/pulls/{number}/comments/{comment_id}/replies",
         {"body": body.rstrip() + FOOTER}, method="POST")
    return {"replied": comment_id}


def resolve(thread_id, reason="ADDRESSED"):
    if reason not in REASONS:
        sys.exit(f"reason must be one of {REASONS}")
    q = ("mutation($id:ID!){resolveReviewThread(input:{threadId:$id,resolutionReason:%s})"
         "{thread{isResolved}}}" % reason)
    return gql(q, {"id": thread_id})["resolveReviewThread"]["thread"]


def main(argv):
    if not argv:
        sys.exit(__doc__)
    cmd, args = argv[0], argv[1:]
    if cmd == "request" and len(args) == 2:
        out = request(args[0], int(args[1]))
    elif cmd == "status" and len(args) == 2:
        out = status(args[0], int(args[1]))
    elif cmd == "threads" and len(args) == 2:
        out = threads(args[0], int(args[1]))
    elif cmd == "reply" and len(args) == 4:
        with open(args[3]) as f:
            out = reply(args[0], int(args[1]), int(args[2]), f.read())
    elif cmd == "resolve" and len(args) in (1, 2):
        out = resolve(*args)
    else:
        sys.exit(__doc__)
    print(json.dumps(out, indent=1))


if __name__ == "__main__":
    main(sys.argv[1:])
